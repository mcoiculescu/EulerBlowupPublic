#!/usr/bin/env python3
"""Generate the spine artefacts from formalization/spine.json.

Usage: spine_gen.py CHECKOUT [--spine] [--verify] [--ledger] [--numbers AUXFILE AUXFILE2]

--spine   writes formalization/lean/TorusEuler/Paper/Spine.lean: one spine node per row,
          `theorem <decl> : <statement> := <proof> <cited spine nodes>`.
--verify  writes formalization/lean/VerifySpine.lean, the checker.
--ledger  writes formalization/paper-coverage-latest.md.
"""
import json, sys
from pathlib import Path

co = Path(sys.argv[1])
flags = set(sys.argv[2:])
data = json.loads((co / "formalization/spine.json").read_text())
rows = data["rows"]
by_num = {r["number"]: r for r in rows}

def text_decl(name):
    return f"TorusEuler.Paper.Text.{name}"

def library(r):
    # rows proved from the library, not one-to-one (decision D28, which superseded D25): no hypotheses, not checked for
    # frontier or bypass; what the TeX proof cites is recorded in tex_cites / tex_text_cites
    return r.get("spine") == "library"

def frontier(r):
    if library(r):
        return []
    out = [by_num[c]["decl"] for c in r["cites"]]
    out += [text_decl(t) for t in r.get("text_cites", [])]
    return out

def short(decl):
    return decl[len("TorusEuler.Paper."):] if decl.startswith("TorusEuler.Paper.") else decl

def proof_name(r):
    base = r["decl"].replace("TorusEuler.Paper.", "TorusEuler.Paper.Proof.", 1)
    if r["decl"].startswith("TorusEuler.Paper.Aux."):
        base = r["decl"].replace("TorusEuler.Paper.Aux.", "TorusEuler.Paper.Aux.Proof.", 1)
    if r["decl"].startswith("TorusEuler.Paper.Text."):
        base = r["decl"].replace("TorusEuler.Paper.Text.", "TorusEuler.Paper.Proof.Text.", 1)
    return base + ("_of" if frontier(r) else "")

def order(rows):
    # topological order of rows by frontier (spine nodes must be defined before use)
    decl_row = {r["decl"]: r for r in rows}
    seen, out = set(), []
    def visit(r, stack=()):
        if r["decl"] in seen:
            return
        if r["decl"] in stack:
            sys.exit(f"citation cycle through {r['number']}")
        for d in frontier(r):
            if d not in decl_row:
                sys.exit(f"{r['number']} cites unknown node {d}")
            visit(decl_row[d], stack + (r["decl"],))
        seen.add(r["decl"]); out.append(r)
    for r in rows:
        visit(r)
    return out

if "--spine" in flags:
    lines = ["import TorusEuler.Paper.All", "",
             "/-! The proof spine of the latest manuscript.",
             "",
             "Generated from `formalization/spine.json` by `spine_gen.py`; do not edit by hand.",
             "Each numbered result is the conditional proof of its statement applied to the",
             "spine nodes of exactly the results its TeX proof cites. -/", ""]
    for r in order(rows):
        args = " ".join(f"@{d}" if False else d for d in frontier(r))
        kind = r["kind"]
        title = r["number"] if kind != "text" else r["number"].replace("Text ", "unnumbered display ")
        lines.append(f"/-- Spine node for {kind if kind != 'text' else ''} {title} "
                     f"(`{r.get('label') or 'unlabeled'}`). Cites: "
                     f"{', '.join(r['cites'] + r.get('text_cites', [])) or 'none'}. -/")
        lines.append(f"theorem {r['decl']} : {r['statement']} :=")
        lines.append(f"  {proof_name(r)}{(' ' + args) if args else ''}")
        lines.append("")
    out = co / "formalization/lean/TorusEuler/Paper/Spine.lean"
    out.write_text("\n".join(lines))
    print("wrote", out)

if "--verify" in flags:
    def arr(xs):
        return "#[" + ", ".join(f"`{x}" for x in xs) + "]"
    rowlines = []
    for r in rows:
        rowlines.append(
            "  { number := \"%s\", decl := `%s, statement := `%s, library := %s,\n    frontier := %s,\n    setting := %s,\n    content := %s }"
            % (r["number"], r["decl"], r["statement"], "true" if library(r) else "false", arr(frontier(r)),
               arr(r.get("setting_predicates", [])), arr(r.get("content", []))))
    src = """import TorusEuler
import Lean.Util.CollectAxioms

/-! Checker for the proof spine of the latest manuscript (generated by `spine_gen.py`
from `formalization/spine.json`; do not edit by hand).

For every numbered result R of the ledger it checks:
1. the spine node `Paper.R` exists and its type is exactly the statement `Paper.Statement.R`;
2. its axioms are among `propext`, `Classical.choice`, `Quot.sound`;
3. **frontier**: the spine nodes reached from its proof, stopping at spine nodes, are
   exactly the nodes of the results the TeX proof cites (the ledger frontier is the argument
   list of the generated node `Proof.R_of ...`, so this check shows that the proof reaches no
   spine node beyond its arguments; that the proof genuinely uses its hypotheses is left to the
   unused-variable linter and to review);
4. **no bypass**: no declaration reached from its proof (stopping at spine nodes) is a
   content lemma of another result;
   (3, 4 and 5 are skipped for the rows marked `library` in the ledger: they are proved from the
   library and are not one-to-one with their TeX proofs);
5. **setting**: the statement mentions the conclusion predicates of the results whose
   objects it is about;
6. **statement purity**: no statement reaches a content lemma of any result.
Finally `TorusEuler.theorem11` must reach exactly the spine node of Theorem 1.1. -/

open Lean Elab Command

structure SpineRow where
  number : String
  decl : Name
  statement : Name
  library : Bool
  frontier : Array Name
  setting : Array Name
  content : Array Name

def spineRows : Array SpineRow := #[
""" + ",\n".join(rowlines) + """]

/-- Project declarations reachable from `root`, not expanding the names in `stop`. -/
def spineReach (env : Environment) (root : Name) (stop : NameSet) : NameSet := Id.run do
  let mut seen : NameSet := {}
  let mut stack := #[root]
  while !stack.isEmpty do
    let n := stack.back!
    stack := stack.pop
    if seen.contains n then continue
    seen := seen.insert n
    if n != root && stop.contains n then continue
    let some ci := env.find? n | continue
    for c in ci.getUsedConstantsAsSet.toList do
      if let some idx := env.getModuleIdxFor? c then
        if (`TorusEuler).isPrefixOf env.header.moduleNames[idx.toNat]! then
          stack := stack.push c
  return seen

run_cmd do
  let env ← getEnv
  let spine : NameSet := spineRows.foldl (fun s r => s.insert r.decl) {}
  let allContent : NameSet := spineRows.foldl (fun s r => r.content.foldl (fun s c => s.insert c) s) {}
  let allowed := [``propext, ``Classical.choice, ``Quot.sound]
  let mut errors : Array String := #[]
  for r in spineRows do
    let some ci := env.find? r.decl
      | errors := errors.push s!"{r.number}: {r.decl} is missing"; continue
    unless ci.type == mkConst r.statement do
      errors := errors.push s!"{r.number}: the type of {r.decl} is not {r.statement}"
    for ax in ← Lean.collectAxioms r.decl do
      unless allowed.contains ax do
        errors := errors.push s!"{r.number}: {r.decl} depends on the axiom {ax}"
    let reached := spineReach env r.decl spine
    if r.library then
      -- proved from the library (not one-to-one): only the type, the axioms and the purity of
      -- the statement are checked
      let stmtReach := spineReach env r.statement {}
      for c in stmtReach.toList do
        if allContent.contains c then
          errors := errors.push s!"{r.number}: the statement reaches the content lemma {c}"
      continue
    let front := reached.toList.filter (fun n => spine.contains n && n != r.decl)
    for f in r.frontier do
      unless front.contains f do
        errors := errors.push s!"{r.number}: the proof does not use the cited node {f}"
    for f in front do
      unless r.frontier.contains f do
        errors := errors.push s!"{r.number}: the proof uses the uncited node {f}"
    for o in spineRows do
      if o.decl != r.decl then
        for c in o.content do
          if reached.contains c then
            errors := errors.push s!"{r.number}: the proof reaches {c}, a content lemma of {o.number}"
    let stmtReach := spineReach env r.statement {}
    for p in r.setting do
      unless stmtReach.contains p do
        errors := errors.push s!"{r.number}: the statement does not mention the setting predicate {p}"
    for c in stmtReach.toList do
      if allContent.contains c then
        errors := errors.push s!"{r.number}: the statement reaches the content lemma {c}"
  let main := spineReach env `TorusEuler.theorem11 spine
  let mainFront := main.toList.filter spine.contains
  unless mainFront == [`TorusEuler.Paper.theorem_1_1] do
    errors := errors.push s!"theorem11 reaches the spine nodes {mainFront}, expected exactly Paper.theorem_1_1"
  if errors.isEmpty then
    let libs := (spineRows.filter (·.library)).map (·.number)
    logInfo m!"Spine verified: {spineRows.size} nodes, standard axioms; frontiers equal to the TeX citations and no bypass for every node except those proved from the library: {libs}"
  else
    throwError (String.intercalate "\\n" errors.toList)
"""
    out = co / "formalization/lean/VerifySpine.lean"
    out.write_text(src)
    print("wrote", out)

if "--ledger" in flags:
    L = ["# Lean coverage of the latest manuscript", "",
         "Generated from [`spine.json`](spine.json) by `spine_gen.py`. The target is the latest",
         f"manuscript ({data['manuscript']}); its auxiliary note is covered outside the spine (below). Each row is one spine",
         "node `TorusEuler.Paper.<name>` of type `TorusEuler.Paper.Statement.<name>`, proved by",
         "applying `Paper.Proof.<name>_of` to the spine nodes of exactly the cited results.",
         "`VerifySpine.lean` checks the frontier, the content lists and the axioms.", "",
         "Rows marked *library* are proved from the library and are not one-to-one with their TeX",
         "proofs; for them the column lists what the TeX proof cites, which the checker does not enforce.",
         "Only Remark 1.2 is a library row (decision D28): the auxiliary note (Aux 1.1-1.3) has no",
         "spine rows; it is formalized by the library theorems `TorusEuler.auxiliaryTerminalSmoothness`,",
         "`TorusEuler.auxiliaryLemma12` and `TorusEuler.auxiliaryLemma13`, which are not spine nodes.",
         "Remark 1.2 is proved from `auxiliaryTerminalSmoothness`.", "",
         "| Result | TeX | Lean | Proof cites | Setting | Notation only | Exports |",
         "| --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        L.append("| %s | `%s` %s | `%s` | %s | %s | %s | %s |" % (
            r["number"], r.get("label") or "unlabeled", r["tex"], short(r["decl"]),
            ("*library*; TeX cites: " + ", ".join(r.get("tex_cites", []) + ["Text " + t for t in r.get("tex_text_cites", [])])) if library(r)
            else (", ".join(r["cites"] + ["Text " + t for t in r.get("text_cites", [])]) or "none"),
            ", ".join(r.get("setting", [])) or "", ", ".join(r.get("notation_only", [])) or "",
            "; ".join(r.get("exports", [])) or ""))
    out = co / "formalization/paper-coverage-latest.md"
    out.write_text("\n".join(L) + "\n")
    print("wrote", out)
